# ── SPARSITY ENFORCEMENT ──────────────────────────────────────────────────────
SKILL_START = 5      # index of first skill column
SKILL_END   = 101    # index after last skill column (96 skills: indices 5..100)
MAX_NONZERO = 28     # ≤30% of 96 skills = 28.8 → 28

def enforce_sparsity(rows, skill_start, skill_end, max_nonzero):
    for row in rows:
        skills = row[skill_start:skill_end]
        nonzero_idx = [i for i, v in enumerate(skills) if v > 0]
        if len(nonzero_idx) > max_nonzero:
            nonzero_idx.sort(key=lambda i: skills[i])
            to_zero = len(nonzero_idx) - max_nonzero
            for i in nonzero_idx[:to_zero]:
                row[skill_start + i] = 0
    return rows

ROWS = enforce_sparsity(ROWS, SKILL_START, SKILL_END, MAX_NONZERO)

