<?php

namespace App\Services;

use Illuminate\Support\Str;

class ReportPdfGenerator
{
    /**
     * Generate a professional, multi-page PDF document in pure PHP.
     *
     * @param  array<string, mixed>  $report
     */
    public static function generate(
        array $report,
        string $studioName = 'SprintStudio',
        string $senderName = 'Studio Member',
        string $orientation = 'portrait'
    ): string {
        $orientation = $report['orientation'] ?? $orientation;
        $generator = new self($report, $studioName, $senderName, $orientation);

        return $generator->build();
    }

    private array $pages = [];

    private int $pageWidth;

    private int $pageHeight;

    public function __construct(
        private array $report,
        private string $studioName,
        private string $senderName,
        private string $orientation = 'portrait'
    ) {
        if ($this->orientation === 'landscape') {
            $this->pageWidth = 842;
            $this->pageHeight = 595;
        } else {
            $this->pageWidth = 595;
            $this->pageHeight = 842;
        }
    }

    public function build(): string
    {
        $this->pages = [];

        $title = $this->report['title'] ?? 'Performance Report';
        $scope = ucfirst($this->report['type'] ?? ($this->report['scope'] ?? 'Project'));
        $completionRate = (int) ($this->report['completion_rate'] ?? 0);
        $totalTasks = (int) ($this->report['total_tasks'] ?? 0);
        $completedTasks = (int) ($this->report['completed_tasks'] ?? 0);
        $unfinishedTasks = (int) ($this->report['unfinished_tasks'] ?? ($totalTasks - $completedTasks));
        $overdueTasks = (int) ($this->report['overdue_tasks'] ?? 0);
        $plannedSp = (int) ($this->report['planned_story_points'] ?? 0);
        $completedSp = (int) ($this->report['completed_story_points'] ?? 0);

        $auditTasks = $this->report['audit_tasks'] ?? ($this->report['tasks_list'] ?? []);
        $isLandscape = $this->orientation === 'landscape';

        // ── PAGE 1: Header + KPI boxes + Executive Insight + Tasks ──
        $page1Ops = [];

        // Header Background Banner
        $bannerHeight = 90;
        $bannerY = $this->pageHeight - $bannerHeight;
        $page1Ops[] = '0.06 0.09 0.16 rg'; // Slate-900
        $page1Ops[] = "0 {$bannerY} {$this->pageWidth} {$bannerHeight} re f";

        // Header Accent Stripe
        $page1Ops[] = '0.31 0.27 0.95 rg'; // Indigo-600
        $stripeY = $bannerY - 4;
        $page1Ops[] = "0 {$stripeY} {$this->pageWidth} 4 re f";

        // Header Text
        $page1Ops[] = '1 1 1 rg';
        $page1Ops[] = 'BT /F2 8.5 Tf 40 '.($this->pageHeight - 28).' Td ('.strtoupper($this->escapePdfText($this->studioName)).'  •  '.strtoupper($this->escapePdfText($scope)).' REPORT) Tj ET';
        $page1Ops[] = 'BT /F2 16 Tf 40 '.($this->pageHeight - 50).' Td ('.Str::limit($this->escapePdfText($title), 65).') Tj ET';
        $page1Ops[] = '0.8 0.85 0.95 rg';
        $page1Ops[] = 'BT /F1 8.5 Tf 40 '.($this->pageHeight - 68).' Td (Generated by '.$this->escapePdfText($this->senderName).'  •  '.date('F j, Y, g:i A').') Tj ET';

        // Section Title
        $currentY = $stripeY - 26;
        $page1Ops[] = '0.06 0.09 0.16 rg';
        $page1Ops[] = "BT /F2 11 Tf 40 {$currentY} Td (EXECUTIVE SUMMARY & KEY METRICS) Tj ET";

        // 4 KPI Metric Boxes
        $currentY -= 55;
        $boxW = $isLandscape ? 175 : 120;
        $boxH = 50;
        $spacing = $isLandscape ? 18 : 10;
        $xStart = 40;

        $page1Ops = array_merge($page1Ops, $this->renderKpiBox($xStart, $currentY, $boxW, $boxH, 'COMPLETION RATE', "{$completionRate}%", '0.31 0.27 0.95'));
        $page1Ops = array_merge($page1Ops, $this->renderKpiBox($xStart + ($boxW + $spacing), $currentY, $boxW, $boxH, 'TASKS COMPLETED', "{$completedTasks} / {$totalTasks}", '0.06 0.09 0.16'));
        $page1Ops = array_merge($page1Ops, $this->renderKpiBox($xStart + ($boxW + $spacing) * 2, $currentY, $boxW, $boxH, 'STORY POINTS', "{$completedSp} / {$plannedSp} pts", '0.06 0.09 0.16'));
        $alertColor = $overdueTasks > 0 ? '0.88 0.11 0.28' : '0.85 0.47 0.02';
        $page1Ops = array_merge($page1Ops, $this->renderKpiBox($xStart + ($boxW + $spacing) * 3, $currentY, $boxW, $boxH, 'UNFINISHED / LATE', "{$unfinishedTasks} ({$overdueTasks} late)", $alertColor));

        // Executive Insight Banner if present
        if (! empty($this->report['executive_insight'])) {
            $currentY -= 32;
            $page1Ops[] = '0.94 0.96 1.0 rg'; // Light blue
            $page1Ops[] = "40 {$currentY} ".($this->pageWidth - 80).' 24 re f';
            $page1Ops[] = '0.2 0.35 0.75 rg';
            $page1Ops[] = 'BT /F2 8 Tf 48 '.($currentY + 8).' Td (FINDINGS: '.Str::limit($this->escapePdfText($this->report['executive_insight']), $isLandscape ? 120 : 80).') Tj ET';
        }

        // Audit Table Section Header
        $currentY -= 28;
        $page1Ops[] = '0.06 0.09 0.16 rg';
        $page1Ops[] = "BT /F2 10 Tf 40 {$currentY} Td (TASK AUDIT & BREAKDOWN) Tj ET";

        // Table Header
        $currentY -= 22;
        $page1Ops = array_merge($page1Ops, $this->renderTableHeader($currentY, $isLandscape));
        $currentY -= 18;

        // Render first page rows
        $rowsPerPage1 = $isLandscape ? 12 : 16;
        $page1Tasks = array_slice($auditTasks, 0, $rowsPerPage1);
        $remainingTasks = array_slice($auditTasks, $rowsPerPage1);

        $rowIdx = 0;
        foreach ($page1Tasks as $t) {
            $page1Ops = array_merge($page1Ops, $this->renderTableRow($t, $currentY, $rowIdx % 2 === 0, $isLandscape));
            $currentY -= 18;
            $rowIdx++;
        }

        $page1Ops[] = $this->renderFooter(1);
        $this->pages[] = implode("\n", $page1Ops);

        // ── SUBSEQUENT PAGES: Remaining Tasks ──
        $rowsPerNextPage = $isLandscape ? 20 : 30;
        $pageNum = 2;

        while (! empty($remainingTasks)) {
            $pageTasks = array_slice($remainingTasks, 0, $rowsPerNextPage);
            $remainingTasks = array_slice($remainingTasks, $rowsPerNextPage);

            $pageOps = [];
            // Minimal Page Header
            $pageOps[] = '0.06 0.09 0.16 rg';
            $pageOps[] = '0 '.($this->pageHeight - 35)." {$this->pageWidth} 35 re f";
            $pageOps[] = '1 1 1 rg';
            $pageOps[] = 'BT /F2 9 Tf 40 '.($this->pageHeight - 22).' Td ('.Str::limit($this->escapePdfText($title), 60).'  •  TASK AUDIT CONTINUED) Tj ET';

            $cY = $this->pageHeight - 65;
            $pageOps = array_merge($pageOps, $this->renderTableHeader($cY, $isLandscape));
            $cY -= 18;

            $rIdx = 0;
            foreach ($pageTasks as $t) {
                $pageOps = array_merge($pageOps, $this->renderTableRow($t, $cY, $rIdx % 2 === 0, $isLandscape));
                $cY -= 18;
                $rIdx++;
            }

            $pageOps[] = $this->renderFooter($pageNum);
            $this->pages[] = implode("\n", $pageOps);
            $pageNum++;
        }

        return $this->compilePdf();
    }

    private function renderKpiBox(int $x, int $y, int $w, int $h, string $label, string $val, string $colorRgb): array
    {
        $ops = [];
        $ops[] = '0.96 0.97 0.98 rg';
        $ops[] = "{$x} {$y} {$w} {$h} re f";
        $ops[] = '0.88 0.90 0.93 RG 0.75 w';
        $ops[] = "{$x} {$y} {$w} {$h} re s";

        // Top accent line
        $ops[] = "{$colorRgb} rg";
        $ops[] = "{$x} ".($y + $h - 3)." {$w} 3 re f";

        // Label
        $ops[] = '0.45 0.50 0.60 rg';
        $ops[] = 'BT /F2 7 Tf '.($x + 8).' '.($y + $h - 14).' Td ('.$this->escapePdfText($label).') Tj ET';

        // Value
        $ops[] = '0.06 0.09 0.16 rg';
        $ops[] = 'BT /F2 13 Tf '.($x + 8).' '.($y + 12).' Td ('.$this->escapePdfText($val).') Tj ET';

        return $ops;
    }

    private function renderTableHeader(int $y, bool $isLandscape): array
    {
        $tableW = $this->pageWidth - 80;
        $ops = [];
        $ops[] = '0.92 0.94 0.97 rg';
        $ops[] = "40 {$y} {$tableW} 16 re f";
        $ops[] = '0.80 0.85 0.90 RG 0.5 w';
        $ops[] = "40 {$y} {$tableW} 16 re s";

        $ops[] = '0.2 0.25 0.35 rg';
        if ($isLandscape) {
            $ops[] = 'BT /F2 7.5 Tf 46 '.($y + 5).' Td (ID) Tj ET';
            $ops[] = 'BT /F2 7.5 Tf 80 '.($y + 5).' Td (TASK TITLE) Tj ET';
            $ops[] = 'BT /F2 7.5 Tf 360 '.($y + 5).' Td (ASSIGNEE) Tj ET';
            $ops[] = 'BT /F2 7.5 Tf 520 '.($y + 5).' Td (STATUS) Tj ET';
            $ops[] = 'BT /F2 7.5 Tf 630 '.($y + 5).' Td (DEADLINE) Tj ET';
            $ops[] = 'BT /F2 7.5 Tf 720 '.($y + 5).' Td (STORY POINTS) Tj ET';
        } else {
            $ops[] = 'BT /F2 7.5 Tf 46 '.($y + 5).' Td (ID) Tj ET';
            $ops[] = 'BT /F2 7.5 Tf 80 '.($y + 5).' Td (TASK TITLE) Tj ET';
            $ops[] = 'BT /F2 7.5 Tf 270 '.($y + 5).' Td (ASSIGNEE) Tj ET';
            $ops[] = 'BT /F2 7.5 Tf 390 '.($y + 5).' Td (STATUS) Tj ET';
            $ops[] = 'BT /F2 7.5 Tf 460 '.($y + 5).' Td (DEADLINE) Tj ET';
            $ops[] = 'BT /F2 7.5 Tf 520 '.($y + 5).' Td (SP) Tj ET';
        }

        return $ops;
    }

    private function renderTableRow(array $task, int $y, bool $isEven, bool $isLandscape): array
    {
        $tableW = $this->pageWidth - 80;
        $ops = [];
        if ($isEven) {
            $ops[] = '0.98 0.98 0.99 rg';
            $ops[] = "40 {$y} {$tableW} 18 re f";
        }
        $ops[] = '0.90 0.92 0.95 RG 0.5 w';
        $ops[] = "40 {$y} m ".($this->pageWidth - 40)." {$y} l S";

        $taskId = '#'.($task['id'] ?? '0');
        $title = Str::limit($task['title'] ?? 'Untitled Task', $isLandscape ? 50 : 32);
        $assignee = Str::limit($task['assigned_employee'] ?? ($task['assignee'] ?? 'Unassigned'), 22);
        $status = ucfirst(str_replace('_', ' ', $task['status'] ?? 'todo'));
        $deadline = ! empty($task['deadline']) ? $task['deadline'] : '—';
        $sp = ($task['final_sp'] ?? ($task['original_sp'] ?? ($task['estimated_hours'] ?? 0))).' pts';

        $ops[] = '0.4 0.45 0.55 rg';
        $ops[] = 'BT /F1 7.5 Tf 46 '.($y + 5).' Td ('.$this->escapePdfText($taskId).') Tj ET';

        $ops[] = '0.1 0.15 0.25 rg';
        $ops[] = 'BT /F2 7.5 Tf 80 '.($y + 5).' Td ('.$this->escapePdfText($title).') Tj ET';

        $ops[] = '0.3 0.35 0.45 rg';
        $assigneeX = $isLandscape ? 360 : 270;
        $ops[] = "BT /F1 7.5 Tf {$assigneeX} ".($y + 5).' Td ('.$this->escapePdfText($assignee).') Tj ET';

        // Status color
        if ($task['status'] === 'completed') {
            $ops[] = '0.06 0.6 0.35 rg';
        } elseif (($task['on_time_status'] ?? '') === 'overdue') {
            $ops[] = '0.85 0.1 0.25 rg';
        } else {
            $ops[] = '0.2 0.4 0.8 rg';
        }
        $statusX = $isLandscape ? 520 : 390;
        $ops[] = "BT /F2 7.5 Tf {$statusX} ".($y + 5).' Td ('.$this->escapePdfText($status).') Tj ET';

        $ops[] = '0.4 0.45 0.55 rg';
        $deadlineX = $isLandscape ? 630 : 460;
        $ops[] = "BT /F1 7.5 Tf {$deadlineX} ".($y + 5).' Td ('.$this->escapePdfText($deadline).') Tj ET';

        $ops[] = '0.1 0.15 0.25 rg';
        $spX = $isLandscape ? 720 : 520;
        $ops[] = "BT /F2 7.5 Tf {$spX} ".($y + 5).' Td ('.$this->escapePdfText($sp).') Tj ET';

        return $ops;
    }

    private function renderFooter(int $pageNum): string
    {
        $escapedStudio = $this->escapePdfText($this->studioName);
        $rightX = $this->pageWidth - 75;

        return implode("\n", [
            '0.60 0.65 0.72 rg',
            'BT /F1 7.5 Tf 40 18 Td (WorkSync SaaS  •  '.$escapedStudio.'  •  Confidential Executive Report) Tj ET',
            'BT /F1 7.5 Tf '.$rightX.' 18 Td (Page '.$pageNum.') Tj ET',
        ]);
    }

    private function escapePdfText(string $str): string
    {
        $str = iconv('UTF-8', 'Windows-1252//TRANSLIT', $str) ?: $str;
        $str = str_replace('\\', '\\\\', $str);
        $str = str_replace('(', '\(', $str);
        $str = str_replace(')', '\)', $str);

        return $str;
    }

    private function compilePdf(): string
    {
        $numPages = count($this->pages);
        $font1Obj = 1;
        $font2Obj = 2;
        $catalogObj = 3;
        $pagesObj = 4;

        $nextObjId = 5;
        $pageObjIds = [];
        $streamObjIds = [];

        for ($i = 0; $i < $numPages; $i++) {
            $pageObjIds[] = $nextObjId++;
            $streamObjIds[] = $nextObjId++;
        }

        $out = "%PDF-1.4\n";
        $offsets = [];

        // Font 1 (Helvetica)
        $offsets[$font1Obj] = strlen($out);
        $out .= "{$font1Obj} 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>\nendobj\n";

        // Font 2 (Helvetica-Bold)
        $offsets[$font2Obj] = strlen($out);
        $out .= "{$font2Obj} 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>\nendobj\n";

        // Catalog
        $offsets[$catalogObj] = strlen($out);
        $out .= "{$catalogObj} 0 obj\n<< /Type /Catalog /Pages {$pagesObj} 0 R >>\nendobj\n";

        // Pages root
        $kidsStr = implode(' 0 R ', $pageObjIds).' 0 R';
        $offsets[$pagesObj] = strlen($out);
        $out .= "{$pagesObj} 0 obj\n<< /Type /Pages /Kids [{$kidsStr}] /Count {$numPages} >>\nendobj\n";

        $mediaBoxStr = "[0 0 {$this->pageWidth} {$this->pageHeight}]";

        // Pages & Streams
        for ($i = 0; $i < $numPages; $i++) {
            $pId = $pageObjIds[$i];
            $sId = $streamObjIds[$i];
            $stream = $this->pages[$i];
            $sLen = strlen($stream);

            $offsets[$pId] = strlen($out);
            $out .= "{$pId} 0 obj\n<< /Type /Page /Parent {$pagesObj} 0 R /MediaBox {$mediaBoxStr} /Contents {$sId} 0 R /Resources << /Font << /F1 {$font1Obj} 0 R /F2 {$font2Obj} 0 R >> >> >>\nendobj\n";

            $offsets[$sId] = strlen($out);
            $out .= "{$sId} 0 obj\n<< /Length {$sLen} >>\nstream\n{$stream}\nendstream\nendobj\n";
        }

        $xrefOffset = strlen($out);
        $totalObjs = $nextObjId;
        $out .= "xref\n0 {$totalObjs}\n";
        $out .= "0000000000 65535 f \n";
        for ($i = 1; $i < $totalObjs; $i++) {
            $out .= sprintf("%010d 00000 n \n", $offsets[$i]);
        }

        $out .= "trailer\n<< /Size {$totalObjs} /Root {$catalogObj} 0 R >>\nstartxref\n{$xrefOffset}\n%%EOF";

        return $out;
    }
}
